"""Paquete publicado vs. repo: lo que se instala, ¿es lo que muestra el código?

Recibe un artefacto ya extraído (tarball de npm, sdist o wheel de PyPI) y el
repo en el commit o tag de esa versión, y marca lo que solo existe o cambia en
el paquete. No ejecuta nada de ninguno de los dos.

- `high`: lo que corre solo al instalar y no coincide con el repo (scripts
  `preinstall`/`install`/`postinstall`, el setup.py o el `[build-system]` de un
  sdist), un `.pth` que ejecuta código en cada arranque de Python, o una
  procedencia firmada que apunta a otro repo.
- `medium`: código que no está en el repo o que cambia, binarios ejecutables
  nuevos, un paquete que casi no se parece al repo que declara.
- `low`: lo generado al compilar (`dist/`, `.min.js`, `.d.ts`): no se puede
  comparar sin construir, pero igual se escanea con los demás chequeos.
"""

from __future__ import annotations

import json
import os
import tomllib
from dataclasses import dataclass, field
from pathlib import Path, PurePosixPath

from jinnexguard.engine.registry import Artifact, same_repo
from jinnexguard.engine.report import Finding, Severity

CATEGORY = "published"
CODE_SUFFIXES = {".js", ".mjs", ".cjs", ".jsx", ".ts", ".mts", ".cts", ".tsx", ".py", ".pyx",
                 ".pxd", ".sh", ".bash", ".zsh", ".ps1", ".bat", ".cmd", ".rb", ".pl", ".php",
                 ".lua", ".go", ".rs", ".c", ".h", ".cc", ".cpp", ".hpp", ".java", ".kt"}
GENERATED_DIRS = {"dist", "build", "lib", "es", "esm", "cjs", "umd", "out", "types", "typings",
                  "bundle", "_cjs", "_esm", "_types", "min"}
GENERATED_SUFFIXES = (".d.ts", ".d.mts", ".d.cts", ".map", ".min.js", ".min.mjs", ".min.css")
GENERATED_MARKERS = (b"generated by", b"@generated", b"do not edit", b"autogenerated",
                     b"auto-generated")
COMPILED_SUFFIXES = {".so", ".pyd", ".dylib", ".dll"}
EXECUTABLE_MAGIC = (b"\x7fELF", b"MZ", b"\xcf\xfa\xed\xfe", b"\xce\xfa\xed\xfe",
                    b"\xca\xfe\xba\xbe", b"\xfe\xed\xfa\xcf")
NPM_AUTORUN = ("preinstall", "install", "postinstall")
# Si menos de esta fracción del código coincide con el repo, el paquete no parece salir de él.
STARJACK_MATCH_RATIO = 0.2
STARJACK_MIN_FILES = 5
MAX_HASH_BYTES = 50_000_000


@dataclass
class Comparison:
    findings: list[Finding] = field(default_factory=list)
    identical: set[str] = field(default_factory=set)      # rutas del paquete iguales al repo
    stats: dict = field(default_factory=dict)


def _read(path: Path) -> bytes | None:
    try:
        if path.is_symlink() or not path.is_file() or path.stat().st_size > MAX_HASH_BYTES:
            return None
        return path.read_bytes()
    except OSError:
        return None


def _normalized(data: bytes) -> bytes:
    return data.replace(b"\r\n", b"\n")


def _walk_files(root: Path) -> list[PurePosixPath]:
    found = []
    for current, dirs, files in os.walk(root):
        dirs[:] = [d for d in dirs if d != ".git"]
        for name in files:
            found.append(PurePosixPath((Path(current) / name).relative_to(root).as_posix()))
    return sorted(found)


class RepoIndex:
    """Los archivos del repo (o de su subcarpeta) para buscar el par de cada archivo del paquete."""

    def __init__(self, root: Path, files: list[PurePosixPath], subdir: str = ""):
        self.root = root
        prefix = PurePosixPath(subdir) if subdir else None
        self.files = [f for f in files if prefix is None or f.is_relative_to(prefix)]
        self.prefix = prefix
        self.by_name: dict[str, list[PurePosixPath]] = {}
        for item in self.files:
            self.by_name.setdefault(item.name, []).append(item)

    def match(self, path: PurePosixPath, content: bytes | None) -> PurePosixPath | None:
        exact = self.prefix / path if self.prefix else path
        if exact in set(self.by_name.get(path.name, ())):
            return exact
        # Un wheel instala `pkg/x.py` que en el repo vive en `src/pkg/x.py`: por sufijo.
        candidates = [c for c in self.by_name.get(path.name, ())
                      if c.parts[-len(path.parts):] == path.parts]
        if not candidates and len(path.parts) == 1:
            return None
        if len(path.parts) == 1 and len(candidates) > 1:
            same = [c for c in candidates if content is not None
                    and self.content(c) == _normalized(content)]
            return same[0] if same else None
        return min(candidates, key=lambda c: len(c.parts)) if candidates else None

    def content(self, path: PurePosixPath) -> bytes | None:
        data = _read(self.root.joinpath(*path.parts))
        return None if data is None else _normalized(data)


def _is_code(path: PurePosixPath, data: bytes) -> bool:
    return path.suffix.lower() in CODE_SUFFIXES or data.startswith(b"#!")


def _is_generated(path: PurePosixPath, data: bytes, package_files: set[PurePosixPath]) -> bool:
    name = path.name.lower()
    if name.endswith(GENERATED_SUFFIXES) or GENERATED_DIRS.intersection(p.lower() for p in path.parts[:-1]):
        return True
    # Un .js con su .d.ts (o su .map) al lado salió de compilar TypeScript, esté donde esté.
    stem = path.name.rsplit(".", 1)[0]
    declarations = {".js": ".d.ts", ".cjs": ".d.cts", ".mjs": ".d.mts"}
    if path.suffix in declarations and (
            path.with_name(stem + declarations[path.suffix]) in package_files
            or path.with_name(stem + ".d.ts") in package_files
            or path.with_name(path.name + ".map") in package_files):
        return True
    head = data[:600].lower()
    return any(marker in head for marker in GENERATED_MARKERS)


def _first_new_line(package: bytes, repo: bytes) -> tuple[int | None, str]:
    """La primera línea del paquete que no aparece en el archivo del repo, como evidencia."""
    known = {line.strip() for line in repo.decode("utf-8", "replace").splitlines()}
    for number, line in enumerate(package.decode("utf-8", "replace").splitlines(), start=1):
        if line.strip() and line.strip() not in known:
            return number, "+ " + line.strip()[:160]
    return None, "same lines in a different order, or the package lacks lines from the repo"


def _matching_path(artifact: Artifact, path: PurePosixPath) -> PurePosixPath | None:
    """La ruta del wheel tal como quedaría en el repo; None para metadatos del empaquetado."""
    parts = path.parts
    if artifact.kind == "wheel":
        if parts[0].endswith(".dist-info"):
            return None
        if parts[0].endswith(".data") and len(parts) > 2:
            return PurePosixPath(*parts[2:]) if parts[1] in ("purelib", "platlib") \
                else PurePosixPath(parts[-1])
    if artifact.kind == "sdist":
        if parts[0] == "PKG-INFO" or parts[0].endswith(".egg-info") or \
                (len(parts) > 1 and parts[-2].endswith(".egg-info")):
            return None
    return path


def _scripts(data: bytes | None) -> dict | None:
    try:
        scripts = json.loads(data or b"null")
        scripts = scripts.get("scripts") if isinstance(scripts, dict) else None
    except ValueError:
        return None
    return scripts if isinstance(scripts, dict) else {}


def _build_system(data: bytes | None) -> dict | None:
    try:
        return tomllib.loads((data or b"").decode("utf-8", "replace")).get("build-system")
    except tomllib.TOMLDecodeError:
        return None


def _special(artifact: Artifact, label: str, path: PurePosixPath, data: bytes,
             repo_data: bytes | None, findings: list[Finding]) -> bool:
    """Archivos que se comparan por lo que ejecutan, no byte a byte. True si ya se trató."""
    where = f"{label}/{path}"
    if artifact.kind == "npm" and path == PurePosixPath("package.json"):
        published, declared = _scripts(data) or {}, _scripts(repo_data)
        if declared is None:
            return True   # sin package.json en el repo: install_scripts ya marca los del paquete
        for name in NPM_AUTORUN:
            if name in published and published[name] != declared.get(name):
                verb = "that differs from the" if name in declared else "that is not in the"
                findings.append(Finding(
                    Severity.HIGH, CATEGORY,
                    f"The published package has a '{name}' {verb} repo ({where})",
                    "npm runs it on its own at install. Whoever reads the repo does not see this "
                    "command: it is exactly the trick of publishing something other than what "
                    "GitHub shows.",
                    evidence=f"{name}: {published[name]}"
                             + (f"  (repo: {declared[name]})" if name in declared else ""),
                    path=where))
        return True
    if artifact.kind == "sdist" and path == PurePosixPath("setup.py"):
        if repo_data is None or _normalized(data) != repo_data:
            line, evidence = _first_new_line(data, repo_data or b"")
            findings.append(Finding(
                Severity.HIGH, CATEGORY,
                f"The package's setup.py {'differs from the' if repo_data else 'is not in the'} repo ({where})",
                "`pip install` of this sdist runs its setup.py. The published one is not the "
                "one the repo shows for this version.",
                evidence=evidence, path=where, line=line))
        return True
    if artifact.kind == "sdist" and path == PurePosixPath("pyproject.toml"):
        published, declared = _build_system(data), _build_system(repo_data)
        if published and published != declared:
            findings.append(Finding(
                Severity.HIGH, CATEGORY,
                f"The package's [build-system] differs from the repo ({where})",
                "The build backend runs when the sdist is installed; the published one does not "
                "match the repo's for this version.",
                evidence=json.dumps(published, ensure_ascii=False)[:200], path=where))
        return True
    if artifact.kind == "wheel" and path.suffix == ".pth":
        imports = [line.strip() for line in data.decode("utf-8", "replace").splitlines()
                   if line.lstrip().startswith(("import ", "import\t"))]
        if imports:
            same = repo_data is not None and _normalized(data) == repo_data
            findings.append(Finding(
                Severity.MEDIUM if same else Severity.HIGH, CATEGORY,
                f".pth file that runs code when Python starts ({where})",
                "Python runs the `import` lines of a .pth file on EVERY interpreter start, "
                "even if you never import the package. It is a known persistence mechanism."
                + (" It is the same in the repo." if same else " The repo does not have it."),
                evidence=imports[0][:160], path=where))
        return True
    return False


def compare(artifact: Artifact, package_root: Path, repo: RepoIndex | None, *,
            exact_ref: bool = True) -> Comparison:
    """Compara un artefacto extraído con el repo. `exact_ref=False` si el repo no está en la versión."""
    result = Comparison()
    label = artifact.label
    stats = {"identical": 0, "differ": 0, "only_in_package": 0, "generated": 0,
             "compiled": 0, "ignored": 0, "not_compared": 0}
    differ_severity = Severity.MEDIUM if exact_ref else Severity.LOW
    grouped_generated: list[str] = []
    package_files = _walk_files(package_root)
    package_set = set(package_files)
    for path in package_files:
        data = _read(package_root.joinpath(*path.parts))
        mapped = _matching_path(artifact, path)
        if data is None or mapped is None:
            stats["ignored"] += 1
            continue
        where = f"{label}/{path}"
        if repo is None:
            # Sin repo no hay "distinto" ni "falta en el repo": solo lo que es riesgoso por sí mismo.
            if artifact.kind == "wheel" and path.suffix == ".pth":
                _special(artifact, label, path, data, None, result.findings)
            stats["not_compared"] += 1
            continue
        repo_path = repo.match(mapped, data)
        repo_data = repo.content(repo_path) if repo_path else None
        if _special(artifact, label, path, data, repo_data, result.findings):
            continue
        if repo_data is not None and _normalized(data) == repo_data:
            stats["identical"] += 1
            result.identical.add(str(path))
            continue
        binary = b"\x00" in data[:1024]
        if binary:
            if path.suffix.lower() in COMPILED_SUFFIXES and artifact.kind == "wheel":
                stats["compiled"] += 1
            elif data.startswith(EXECUTABLE_MAGIC) and repo_data is None:
                result.findings.append(Finding(
                    Severity.MEDIUM, CATEGORY,
                    f"Executable binary that is not in the repo ({where})",
                    "The package ships a compiled executable that does not come from the repo's "
                    "code: there is no way to read what it does. Many packages ship legitimate "
                    "prebuilt binaries; confirm the project explains it.",
                    evidence=f"{len(data)} bytes, header {data[:4].hex()}", path=where))
                stats["only_in_package"] += 1
            else:
                stats["ignored"] += 1
            continue
        if not _is_code(path, data):
            stats["ignored"] += 1
            continue
        if repo_data is not None:
            stats["differ"] += 1
            line, evidence = _first_new_line(data, repo_data)
            result.findings.append(Finding(
                differ_severity, CATEGORY,
                f"Package code differs from the repo ({where})",
                f"Compared with the repo's {repo_path}. "
                + ("It may be a build change (version, paths), or code the repo does not show."
                   if exact_ref else "The repo is not at this exact version: the difference may "
                   "just be a later change."),
                evidence=evidence, path=where, line=line))
        elif _is_generated(path, data, package_set):
            stats["generated"] += 1
            grouped_generated.append(where)
        else:
            stats["only_in_package"] += 1
            result.findings.append(Finding(
                Severity.MEDIUM, CATEGORY,
                f"Package code that is not in the repo ({where})",
                "It gets installed but does not appear in the repo: nobody who read GitHub "
                "reviewed it.",
                evidence=data.decode("utf-8", "replace").strip().splitlines()[0][:160]
                if data.strip() else "", path=where))
    if grouped_generated:
        result.findings.append(Finding(
            Severity.LOW, CATEGORY,
            f"{len(grouped_generated)} build-generated files in {label}",
            "dist/, .min.js, .d.ts and the like are not in the repo because the build produces "
            "them: they cannot be compared without building. They were scanned by the other "
            "checks.",
            evidence=", ".join(grouped_generated[:5])
                     + (f" … (+{len(grouped_generated) - 5})" if len(grouped_generated) > 5 else "")))
    considered = stats["identical"] + stats["differ"] + stats["only_in_package"]
    if repo is not None and considered >= STARJACK_MIN_FILES and \
            stats["identical"] / considered < STARJACK_MATCH_RATIO:
        result.findings.append(Finding(
            Severity.MEDIUM, CATEGORY,
            f"The package barely resembles the repo it declares ({label})",
            "Very little of the published code matches the repo. Anyone can put a famous repo's "
            "URL in their package to borrow its reputation (starjacking).",
            evidence=f"{stats['identical']} of {considered} code files identical"))
    result.stats = stats
    return result


def infer_npm_dir(root: Path, files: list[PurePosixPath], name: str) -> str:
    """La carpeta del monorepo cuyo package.json se llama `name` ("" si es la raíz o no aparece).

    Muchos paquetes de monorepos no declaran `repository.directory`; sin esto se
    compararían contra la raíz y todo saldría distinto.
    """
    best: str | None = None
    for path in files:
        if path.name != "package.json" or "node_modules" in path.parts:
            continue
        data = _read(root.joinpath(*path.parts))
        try:
            declared = json.loads(data or b"null")
        except ValueError:
            continue
        if isinstance(declared, dict) and declared.get("name") == name:
            parent = str(path.parent) if len(path.parts) > 1 else ""
            if best is None or len(parent) < len(best):
                best = parent
    return best or ""


def provenance_findings(label: str, declared_repo: str | None, provenance: dict | None
                        ) -> list[Finding]:
    """Una procedencia que contradice el repo declarado es la señal más directa de todas."""
    if not provenance or not provenance.get("repository") or not declared_repo:
        return []
    if same_repo(provenance["repository"], declared_repo):
        return []
    return [Finding(
        Severity.HIGH, CATEGORY,
        f"The package's provenance points at another repo ({label})",
        "The registry says this package was built in a different repo from the one its page "
        "declares. JinnexGuard reads the attestation but does not verify its signature.",
        evidence=f"provenance: {provenance['repository']} · declared: {declared_repo}")]
